# setup_codex_provider.py

from __future__ import annotations

import argparse
import getpass
import json
import os
import shutil
import sys
import tempfile
from datetime import datetime
from pathlib import Path
from urllib.parse import urlparse


class CodexProviderConfigurator:
    """建立或更新 Codex custom provider 設定。"""

    DEFAULT_PROVIDER_ID = "custom-openai"
    DEFAULT_PROVIDER_NAME = "Custom OpenAI Provider"

    SUPPORTED_INTERFACES = {
        "responses": "responses",
        "response": "responses",
        "responses_api": "responses",
    }

    def __init__(
        self,
        api_url: str,
        api_key: str,
        codex_home: Path | None = None,
        provider_id: str = DEFAULT_PROVIDER_ID,
        provider_name: str = DEFAULT_PROVIDER_NAME,
    ) -> None:
        self.api_url = self._validate_api_url(api_url)
        self.api_key = self._validate_api_key(api_key)

        self.codex_home = codex_home or self._default_codex_home()
        self.config_path = self.codex_home / "config.toml"

        self.provider_id = provider_id
        self.provider_name = provider_name

    @staticmethod
    def _default_codex_home() -> Path:
        configured_home = os.environ.get("CODEX_HOME")

        if configured_home:
            return Path(configured_home).expanduser()

        return Path.home() / ".codex"

    @staticmethod
    def _validate_api_url(value: str) -> str:
        value = value.strip().rstrip("/")
        parsed = urlparse(value)

        if parsed.scheme not in {"http", "https"} or not parsed.netloc:
            raise ValueError(
                "API 必須是完整 URL，例如：https://api.example.com/v1"
            )

        return value

    @classmethod
    def _validate_interface(cls, value: str) -> str:
        normalized = (
            value.strip()
            .lower()
            .replace("-", "_")
            .replace(" ", "_")
        )

        if normalized not in cls.SUPPORTED_INTERFACES:
            raise ValueError(
                "目前 Codex custom provider 只支援 Responses API，"
                "請輸入：responses"
            )

        return cls.SUPPORTED_INTERFACES[normalized]

    @staticmethod
    def _validate_api_key(value: str) -> str:
        value = value.strip()

        if not value:
            raise ValueError("API Key 不可為空")

        return value

    @staticmethod
    def _toml_string(value: str) -> str:
        return json.dumps(value, ensure_ascii=False)

    def render_config(self) -> str:
        provider_id = self.provider_id

        return f"""# Generated by setup_codex_provider.py
# API key is stored directly in this file.
# Keep this file private and do not commit it to Git.

model_provider = {self._toml_string(provider_id)}

[model_providers.{provider_id}]
name = {self._toml_string(self.provider_name)}
base_url = {self._toml_string(self.api_url)}
experimental_bearer_token = {self._toml_string(self.api_key)}
supports_websockets = false
"""

    def _choose_backup_path(self) -> Path:
        backup_path = self.config_path.with_name(
            self.config_path.name + ".bak"
        )

        if not backup_path.exists():
            return backup_path

        timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
        backup_path = self.config_path.with_name(
            f"{self.config_path.name}.{timestamp}.bak"
        )

        counter = 1
        while backup_path.exists():
            backup_path = self.config_path.with_name(
                f"{self.config_path.name}.{timestamp}.{counter}.bak"
            )
            counter += 1

        return backup_path

    def backup_existing_config(self) -> Path | None:
        if not self.config_path.exists():
            return None

        backup_path = self._choose_backup_path()
        shutil.copy2(self.config_path, backup_path)
        return backup_path

    def _write_atomically(self, content: str) -> None:
        temporary_path: Path | None = None

        try:
            with tempfile.NamedTemporaryFile(
                mode="w",
                encoding="utf-8",
                newline="\n",
                dir=self.codex_home,
                delete=False,
            ) as temporary_file:
                temporary_file.write(content)
                temporary_file.flush()
                os.fsync(temporary_file.fileno())
                temporary_path = Path(temporary_file.name)

            os.replace(temporary_path, self.config_path)

        finally:
            if temporary_path and temporary_path.exists():
                temporary_path.unlink()

    def generate(self, dry_run: bool = False) -> Path | None:
        content = self.render_config()

        if dry_run:
            print(content)
            return None

        self.codex_home.mkdir(parents=True, exist_ok=True)

        backup_path = self.backup_existing_config()
        self._write_atomically(content)

        print(f"已生成：{self.config_path}")

        if backup_path:
            print(f"原設定已備份：{backup_path}")

        print("注意：API Key 目前直接儲存在 config.toml 中。")
        print("請勿將此檔案提交到 Git。")

        return self.config_path

    @classmethod
    def from_interactive_input(
        cls,
        api_url: str | None = None,
        api_key: str | None = None,
        codex_home: Path | None = None,
    ) -> "CodexProviderConfigurator":
        api_url = api_url or input("API Base URL: ")

        api_key = api_key or getpass.getpass("API Key: ")

        return cls(
            api_url=api_url,
            api_key=api_key,
            codex_home=codex_home,
        )


def parse_arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate Codex custom provider config.toml"
    )

    parser.add_argument(
        "--api",
        help="API Base URL，例如：https://api.example.com/v1",
    )
    parser.add_argument(
        "--key",
        help="API Key。不提供時會以隱藏輸入方式詢問",
    )
    parser.add_argument(
        "--codex-home",
        help="自訂 CODEX_HOME 目錄",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="只顯示設定內容，不寫入檔案",
    )

    return parser.parse_args()


def main() -> int:
    args = parse_arguments()

    try:
        codex_home = (
            Path(args.codex_home).expanduser()
            if args.codex_home
            else None
        )

        configurator = CodexProviderConfigurator.from_interactive_input(
            api_url=args.api,
            api_key=args.key,
            codex_home=codex_home,
        )

        configurator.generate(dry_run=args.dry_run)
        return 0

    except KeyboardInterrupt:
        print("\n已取消。")
        return 130

    except Exception as error:
        print(f"錯誤：{error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())